        main = p.databases[0]
        m["tps"] = tps
        m["xact_commit"] = tps * 0.984
        m["xact_rollback"] = tps * (0.016 + 0.004 * n("rb"))
        for db in p.databases:
            share = 0.965 if db == main else (0.03 if db != "postgres" else 0.005)
            m[f"tps[{db}]"] = tps * share
        m["max_connections"] = float(p.max_connections)
        conn_base = {"orders-prod": (140, 0.12), "payments-prod": (180, 0.04), "payments-replica": (40, 0.12), "inventory-prod": (160, 0.25),
                     "analytics-staging": (22, 0.30), "crm-prod": (60, 0.20), "ledger-dev": (8, 0.20)}.get(p.id, (70, 0.08))
        conns = conn_base[0] + conn_base[1] * tps + 6 * n("conn", 300) + 2 * j("conn")
        active = max(1.0, tps * {"analytics-staging": 0.09, "payments-replica": 0.012}.get(p.id, 0.0025) + 2 + 1.5 * n("act", 120))
        idle_tx = max(0.0, round(1.2 + 1.4 * n("itx", 300)))
        m["sessions_by_state[active]"] = round(active)
        m["sessions_by_state[idle in transaction]"] = idle_tx
        m["sessions_by_state[idle]"] = max(0.0, round(conns - active - idle_tx))
        m["active_connections"] = round(conns)
        for db in p.databases:
            m[f"numbackends[{db}]"] = round(conns * (0.96 if db == main else 0.02))
        m["blocked_sessions"] = 1.0 if j("blk") > 0.985 else 0.0
        m["lock_wait_max_sec"] = 1.2 if m["blocked_sessions"] else 0.0
        q_typ = {"analytics-staging": 140.0, "payments-replica": 45.0}.get(p.id, 1.6)
        m["longest_query_time_sec"] = max(0.05, q_typ * (1 + 0.6 * n("lq", 180)) + abs(j("lq")) * q_typ * 0.2)
        m["longest_transaction_time_sec"] = m["longest_query_time_sec"] + 0.8 + abs(n("lt", 240)) * 2
