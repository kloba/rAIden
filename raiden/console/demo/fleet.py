        period = 150e6 / max(1.0, xid_rate)
        phase = ((ts + _u(src.id, "xidphase") * period) % period) / period
        m["maximum_used_transactionIDs"] = 48e6 + 152e6 * phase
        m["max_multixact_age"] = 4e6 + 3e6 * (1 + n("mx", 7200))
        m["prepared_xact_oldest_seconds"] = 0.4 if p.id == "inventory-prod" and j("2pc") > 0.6 else 0.0
        m["pending_restart_settings"] = 2.0 if p.id == "ledger-dev" else 0.0
        m["checksum_failures"] = 0.0
        hit = {"analytics-staging": 97.6, "payments-replica": 98.9, "billing-prod": 93.4}.get(p.id, 99.62) + 0.18 * n("hit", 300)
        m["cache_hit_ratio"] = min(99.99, hit)
        m["blks_hit"] = tps * 140
        m["blks_read"] = m["blks_hit"] * (100 - hit) / hit
        m["tup_inserted"] = tps * 1.3
        m["tup_updated"] = tps * 0.6
        m["tup_deleted"] = tps * 0.05
        m["tup_fetched"] = tps * 18
        m["tup_returned"] = tps * 160
        m["deadlocks"] = 1.0 if p.id == "orders-prod" and j("dl") > 0.992 else 0.0
        etl = p.id == "analytics-staging" and f > 0.7
        m["temp_files"] = (6 + 4 * n("tf")) if etl else (0.4 if p.id == "crm-prod" and j("tf") > 0.7 else 0.0)
        m["temp_bytes"] = m["temp_files"] * 180e6
        m["rollback_percent"] = 100 * m["xact_rollback"] / max(1e-6, m["xact_commit"] + m["xact_rollback"])
        m["wal_bytes_per_second"] = tps * 1900 * (1 + 0.1 * n("wal"))
