def _u(*parts: Any) -> float:
    """Deterministic uniform [0, 1) from any key."""
    h = hashlib.blake2b(repr(parts).encode(), digest_size=8).digest()
    return int.from_bytes(h, "big") / 2**64


def noise(key: Any, ts: float, period: float = 600.0) -> float:
    """Smooth value noise in [-1, 1]."""
    k = math.floor(ts / period)
    f = ts / period - k
    a, b = _u(key, k) * 2 - 1, _u(key, k + 1) * 2 - 1
    w = (1 - math.cos(math.pi * f)) / 2
    return a * (1 - w) + b * w


def jitter(key: Any, ts: float) -> float:
    return _u(key, int(ts // 15)) * 2 - 1


def load_factor(p: Profile, ts: float) -> float:
    lt = time.gmtime(ts)
    hour = lt.tm_hour + lt.tm_min / 60
    peak = 3.5 if p.id == "analytics-staging" else 14.5  # the ETL runs at night, the shops by day
    phase = 2 * math.pi * (hour - peak) / 24
    f = 0.30 + 0.70 * ((1 + math.cos(phase)) / 2) ** 1.4
    if lt.tm_wday >= 5:
        f *= 0.72
    return f * (1 + 0.05 * noise((p.id, "load"), ts, 1800))


def _bell(x: float) -> float:
    """0 -> 1 -> 0 over x in [0, 1], with a plateau."""
    if x <= 0 or x >= 1:
        return 0.0
    if x < 0.25:
        return x / 0.25
    if x > 0.75:
        return (1 - x) / 0.25
    return 1.0


